"""Generate the lookup tables of the integer softmax (generated/apan_position_softmax_table.h).

exp(-D) is evaluated with D = integer part + 8-bit digit + 8-bit digit + 11-bit digit, all in Q27:
    exp(-D) = A[i] * B1[j] * B2[k] * (1 - t)      with every factor in Q31.
"""
import math
from pathlib import Path

Q = 31
OUT = Path(__file__).resolve().parents[1] / "generated" / "apan_position_softmax_table.h"


def q31(value: float) -> int:
    return int(round(value * (1 << Q)))


def table(name: str, values: list[int], comment: str) -> str:
    rows = []
    for start in range(0, len(values), 8):
        rows.append("    " + ", ".join(f"0x{v:08X}UL" for v in values[start:start + 8]))
    return f"/* {comment} */\nstatic const uint32_t {name}[{len(values)}] = {{\n" + ",\n".join(rows) + "\n};\n"


def main() -> None:
    a = [q31(math.exp(-i)) for i in range(25)]
    b1 = [q31(math.exp(-j / 256.0)) for j in range(256)]
    b2 = [q31(math.exp(-k / 65536.0)) for k in range(256)]
    text = (
        "/* Generated by tools/generate_softmax_tables.py. Do not edit. */\n"
        "#ifndef APAN_POSITION_SOFTMAX_TABLE_H\n#define APAN_POSITION_SOFTMAX_TABLE_H\n\n#include <stdint.h>\n\n"
        + table("apan_softmax_exp_int", a, "exp(-i), i = 0..24, Q31")
        + "\n" + table("apan_softmax_exp_hi", b1, "exp(-j / 256), j = 0..255, Q31")
        + "\n" + table("apan_softmax_exp_mid", b2, "exp(-k / 65536), k = 0..255, Q31")
        + "\n#endif\n"
    )
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(OUT)


if __name__ == "__main__":
    main()
