"""Generate the ODL prior for the deployed 128-32-60 position model."""

from __future__ import annotations

import argparse
import zlib
from pathlib import Path

import numpy as np

from .dummy_model_pipeline import from_bfloat16_bits, quantize_bfloat16
from .odl_calibration_experiment import initial_p
from .pc_position_grid_runtime import DEFAULT_SESSION_IDS, load_position_dataset, parse_session_ids
from .real_model_pipeline import extract_hybrid_features, _c_float_array

CALIBRATION_WEIGHT = 30.0
PRIOR_RIDGE = 1.0
DEFAULT_MODEL = Path("artifacts/device_position_probability_400x300x5/model.npz")
DEFAULT_PRIOR_HEADER = Path("firmware/AcrylicPanCollector/generated/apan_calibration_prior.h")


def export(model_path: Path, sessions_root: Path, prior_header: Path,
           session_ids: tuple[str, ...] = DEFAULT_SESSION_IDS) -> dict:
    with np.load(model_path, allow_pickle=False) as model:
        alpha = from_bfloat16_bits(np.asarray(model["alpha_bfloat16"], dtype=np.uint16))
        beta_bits = np.asarray(model["beta_bfloat16"], dtype=np.uint16)
        mean = np.asarray(model["feature_mean"], dtype=np.float32)
        scale = np.asarray(model["feature_scale"], dtype=np.float32)

    dataset = load_position_dataset(sessions_root, session_ids)
    features = np.stack([extract_hybrid_features(row)[:127] for row in dataset.samples])
    inputs = np.ones((len(features), 128), dtype=np.float32)
    inputs[:, :127] = (features - mean) / scale
    xq = quantize_bfloat16(inputs).astype(np.float64)
    aq = quantize_bfloat16(alpha).astype(np.float64)
    hidden = np.clip(0.2 * (xq @ aq) + 0.5, 0.0, 1.0)
    p0 = initial_p(hidden, PRIOR_RIDGE, CALIBRATION_WEIGHT).astype(np.float32)
    crc = zlib.crc32(np.asarray(beta_bits, dtype="<u2").tobytes()) & 0xFFFFFFFF

    text = f"""/* Generated by python -m sim.position_odl_calibration_prior. Do not edit. */
#ifndef APAN_CALIBRATION_PRIOR_H
#define APAN_CALIBRATION_PRIOR_H
#include <stdint.h>
#define APAN_CALIBRATION_HIDDEN_SIZE {beta_bits.shape[0]}U
#define APAN_CALIBRATION_OUTPUT_SIZE {beta_bits.shape[1]}U
/* Factory beta identity: CRC32 of row-major little-endian bfloat16 bits. */
#define APAN_CALIBRATION_MODEL_CRC32 (0x{crc:08X}UL)
/* P0 = w (G + lambda I)^-1 over {len(dataset.samples)} factory events;
   w = {CALIBRATION_WEIGHT:g}, lambda = {PRIOR_RIDGE:g}. */
"""
    text += _c_float_array("apan_calibration_p0", p0)
    text += "#endif\n"
    prior_header.parent.mkdir(parents=True, exist_ok=True)
    prior_header.write_text(text, encoding="ascii")
    return {
        "model_crc32": f"0x{crc:08X}",
        "factory_events": len(dataset.samples),
        "shape": [int(beta_bits.shape[0]), int(beta_bits.shape[1])],
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sessions", type=Path, default=Path("data/raw/sessions_2point"))
    parser.add_argument("--model", type=Path, default=DEFAULT_MODEL)
    parser.add_argument("--prior-header", type=Path, default=DEFAULT_PRIOR_HEADER)
    parser.add_argument("--session-ids", default="default")
    args = parser.parse_args()
    print(export(args.model, args.sessions, args.prior_header,
                 parse_session_ids(args.session_ids, args.sessions)))


if __name__ == "__main__":
    main()
