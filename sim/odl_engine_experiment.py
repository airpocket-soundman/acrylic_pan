"""Does the AxlCORE's own ODL (``ODL_StartTrain``) stay stable for the 12-area calibration?

The deployed calibration runs the OS-ELM in float32 on the CPU because the AxlCORE keeps P and beta in
bfloat16 and diverged on the IchiPing board (docs/odl-calibration-experiment-20260927.md).  This experiment
trains the same hits in both the AxlCORE and the CPU float32 OS-ELM on the board, starting from the same
factory beta and P0, and compares the two.  Firmware: ``APAN_ODL_EXPERIMENT`` in
``firmware/AcrylicPanCollector/include/apan_odl_experiment.h``.

    python -m sim.odl_engine_experiment export          # write the hits into the firmware header
    python -m sim.odl_engine_experiment run --port COM3 # run on the board and write the report
    python -m sim.odl_engine_experiment live --port COM3 --rounds 10   # real strikes, guided
"""

from __future__ import annotations

import argparse
import json
import re
import struct
import time
from pathlib import Path

import numpy as np

from .dummy_model_pipeline import (
    from_bfloat16_bits, mcu_reference, quantize_bfloat16, to_bfloat16_bits,
)
from .odl_calibration_experiment import hidden_layer, os_elm_update
from .pc_position_grid_runtime import discover_session_ids, load_position_dataset

MODEL_HEADER = Path("firmware/AcrylicPanCollector/generated/apan_12class_model.h")
PRIOR_HEADER = Path("firmware/AcrylicPanCollector/generated/apan_calibration_prior.h")
DATA_HEADER = Path("firmware/AcrylicPanCollector/generated/apan_odl_experiment_data.h")
REPORT = Path("artifacts/odl_engine_experiment/report.json")
TRIGGER_INDEX = 64
SAMPLE_COUNT = 512
CLASS_COUNT = 12
HIDDEN = 32
ROUNDS = 20            # guided rounds: every round hits all 12 areas once -> 240 hits
TEST_PER_CLASS = 10


def _array(text: str, name: str) -> list[str]:
    match = re.search(rf"{name}\[\d+\] = \{{(.*?)\}};", text, re.S)
    if match is None:
        raise ValueError(f"{name} was not found")
    return [token.strip() for token in match.group(1).replace("\n", " ").split(",") if token.strip()]


def load_model(header: Path = MODEL_HEADER, prior: Path = PRIOR_HEADER) -> dict:
    text = header.read_text(encoding="ascii")
    hex_bits = lambda name: np.asarray([int(value, 16) for value in _array(text, name)], dtype=np.uint16)
    floats = lambda source, name: np.asarray(
        [float(value.rstrip("Ff")) for value in _array(source, name)], dtype=np.float64)
    return {
        "alpha": from_bfloat16_bits(hex_bits("apan_model_alpha")).reshape(128, HIDDEN).astype(np.float64),
        "beta_bits": hex_bits("apan_model_beta").reshape(HIDDEN, CLASS_COUNT),
        "mean": floats(text, "apan_model_feature_mean"),
        "scale": floats(text, "apan_model_feature_scale"),
        "time_indices": np.asarray([int(value) for value in _array(text, "apan_model_time_indices")]),
        "p0": floats(prior.read_text(encoding="ascii"), "apan_calibration_p0").reshape(HIDDEN, HIDDEN),
    }


def model_inputs(samples: np.ndarray, model: dict) -> np.ndarray:
    """The firmware's preprocessing, ending in bfloat16 bits (what the AxlCORE receives)."""
    baseline = samples[:, :TRIGGER_INDEX].mean(axis=1, keepdims=True)
    centered = samples - baseline
    peak = np.maximum(np.abs(centered[:, TRIGGER_INDEX:]).max(axis=1, keepdims=True), 1.0)
    picked = centered[:, TRIGGER_INDEX + model["time_indices"]] / peak
    return to_bfloat16_bits(((picked - model["mean"]) / model["scale"]).astype(np.float32))


def choose(sessions_root: Path, model: dict) -> dict:
    dataset = load_position_dataset(sessions_root, discover_session_ids(sessions_root))
    bits = model_inputs(dataset.samples[:, :SAMPLE_COUNT], model)
    labels = np.asarray(dataset.labels, dtype=np.int64)
    pool = dataset.repetitions % 5 != 0
    rng = np.random.default_rng(0)
    per_class = {c: rng.choice(np.flatnonzero(pool & (labels == c)), size=ROUNDS, replace=False)
                 for c in range(CLASS_COUNT)}
    train = np.asarray([per_class[c][r] for r in range(ROUNDS) for c in range(CLASS_COUNT)])
    test_rng = np.random.default_rng(1)
    test = np.concatenate([test_rng.choice(np.flatnonzero(~pool & (labels == c)), size=TEST_PER_CLASS, replace=False)
                           for c in range(CLASS_COUNT)])
    return {"train_bits": bits[train], "train_labels": labels[train],
            "test_bits": bits[test], "test_labels": labels[test],
            "dataset_sha256": dataset.dataset_sha256}


def export(sessions_root: Path, header: Path = DATA_HEADER) -> None:
    chosen = choose(sessions_root, load_model())
    bits, labels = chosen["train_bits"], chosen["train_labels"]
    rows = ",\n    ".join("{" + ", ".join(f"0x{int(v):04X}" for v in row) + "}" for row in bits)
    header.write_text(
        "/* Generated by python -m sim.odl_engine_experiment export. Do not edit. */\n"
        "#ifndef APAN_ODL_EXPERIMENT_DATA_H\n#define APAN_ODL_EXPERIMENT_DATA_H\n#include <stdint.h>\n"
        f"/* {len(labels)} guided hits ({ROUNDS} rounds over the 12 areas) from {sessions_root.name}; "
        f"dataset {chosen['dataset_sha256']}. */\n"
        f"#define APAN_ODL_EXPERIMENT_COUNT {len(labels)}U\n"
        f"static const uint8_t apan_odl_experiment_targets[{len(labels)}] = {{\n    "
        + ", ".join(str(int(v)) for v in labels) + "\n};\n"
        f"static const uint16_t apan_odl_experiment_inputs[{len(labels)}][128] = {{\n    {rows}\n}};\n#endif\n",
        encoding="ascii")
    print(f"{header}: {len(labels)} hits")


# ---------------------------------------------------------------------------------------------- board link
OP_BEGIN, OP_RUN, OP_DUMP_ENGINE, OP_DUMP_CPU, OP_DUMP_INPUT = 6, 7, 8, 9, 10


class Board:
    def __init__(self, transport) -> None:
        from pc.acrylic_pan_monitor.calibrate import CalibrationClient
        self.client = CalibrationClient(transport, response_timeout=60.0)
        self.client.set_calibration_mode()

    def _ask(self, operation: int, argument: int = 0) -> bytes:
        from pc.acrylic_pan_monitor.protocol import Frame, MessageType, encode_frame
        sequence = self.client._take_sequence()
        frame = self.client._request(
            encode_frame(Frame(MessageType.CALIBRATION, sequence, bytes([operation, argument]))), sequence)
        if frame.message_type != MessageType.ODL_EXPERIMENT_RESULT or frame.payload[0] != operation:
            raise RuntimeError(f"unexpected reply to operation {operation}: {frame}")
        return frame.payload

    def begin(self) -> None:
        self._ask(OP_BEGIN)

    def run(self, count: int) -> tuple[int, int, int]:
        payload = self._ask(OP_RUN, count)
        updates, engine_us = struct.unpack("<HI", payload[2:8])
        return payload[1], updates, engine_us

    def last_input(self) -> np.ndarray:
        return np.frombuffer(self._ask(OP_DUMP_INPUT)[2:258], dtype="<u2").copy()

    def beta(self) -> tuple[np.ndarray, np.ndarray]:
        engine = b"".join(self._ask(OP_DUMP_ENGINE, part)[2:] for part in range(4))
        cpu = b"".join(self._ask(OP_DUMP_CPU, part)[2:] for part in range(8))
        engine_beta = from_bfloat16_bits(np.frombuffer(engine, dtype="<u2")).reshape(HIDDEN, CLASS_COUNT)
        cpu_beta = np.frombuffer(cpu, dtype="<f4").reshape(HIDDEN, CLASS_COUNT).astype(np.float64)
        return engine_beta.astype(np.float64), cpu_beta


def _accuracy(model: dict, test_bits: np.ndarray, test_labels: np.ndarray, beta: np.ndarray) -> float:
    if not np.isfinite(beta).all():
        return 0.0
    scores = mcu_reference(from_bfloat16_bits(test_bits), model["alpha"].astype(np.float32), beta.astype(np.float32))
    return float(np.mean(np.argmax(scores, axis=1) == test_labels))


def run(sessions_root: Path, port_name: str, updates: int, checkpoint: int, report_path: Path) -> dict:
    import serial

    model = load_model()
    chosen = choose(sessions_root, model)
    train_bits, train_labels = chosen["train_bits"], chosen["train_labels"]
    hidden_all = np.asarray([
        hidden_layer(from_bfloat16_bits(train_bits[i % len(train_labels)][None, :]), model["alpha"])[0]
        for i in range(updates)])
    labels_all = np.asarray([train_labels[i % len(train_labels)] for i in range(updates)])
    beta0 = from_bfloat16_bits(model["beta_bits"]).astype(np.float64)
    references = {
        "float64": lambda n: os_elm_update(beta0, model["p0"], hidden_all[:n], labels_all[:n], "float64")[0],
        "float32_bf16beta": lambda n: os_elm_update(beta0, model["p0"], hidden_all[:n], labels_all[:n],
                                                    "float32_bf16beta")[0],
        "bfloat16": lambda n: os_elm_update(beta0, model["p0"], hidden_all[:n], labels_all[:n], "bfloat16")[0],
    }
    checkpoints = []
    started = time.time()
    with serial.Serial(port_name, 115_200, timeout=0.05, write_timeout=0.5) as port:
        board = Board(port)
        board.begin()
        done = 0
        engine_us_total = 0
        while True:
            engine, cpu = board.beta()
            row = {"updates": done, "engine_us_total": engine_us_total,
                   "engine_nonfinite": int((~np.isfinite(engine)).sum()),
                   "engine_max_abs_beta": float(np.abs(engine).max()),
                   "cpu_max_abs_beta": float(np.abs(cpu).max()),
                   "engine_vs_cpu_max": float(np.abs(engine - cpu).max()),
                   "engine_vs_cpu_mean": float(np.abs(engine - cpu).mean()),
                   "accuracy_engine": _accuracy(model, chosen["test_bits"], chosen["test_labels"], engine),
                   "accuracy_cpu": _accuracy(model, chosen["test_bits"], chosen["test_labels"], cpu)}
            for name, reference in references.items():
                ref = reference(done)
                row[f"engine_vs_{name}_max"] = float(np.abs(engine - ref).max())
                row[f"cpu_vs_{name}_max"] = float(np.abs(cpu - ref).max())
                row[f"accuracy_{name}"] = _accuracy(model, chosen["test_bits"], chosen["test_labels"], ref)
            checkpoints.append(row)
            print(f"{done:4d} updates: engine-vs-cpu max {row['engine_vs_cpu_max']:.4f}, "
                  f"accuracy engine {row['accuracy_engine']:.3f} cpu {row['accuracy_cpu']:.3f} "
                  f"({time.time() - started:.0f}s)", flush=True)
            if done >= updates:
                break
            target = min(done + checkpoint, updates)
            while done < target:
                status, total, engine_us = board.run(min(8, target - done))
                if status != 0:
                    raise RuntimeError(f"board reported status {status} at update {total}")
                engine_us_total += engine_us
                done = total
    report = {"updates": updates, "checkpoint": checkpoint, "train_hits": int(len(train_labels)),
              "test_hits": int(len(chosen["test_labels"])), "dataset_sha256": chosen["dataset_sha256"],
              "factory_accuracy": _accuracy(model, chosen["test_bits"], chosen["test_labels"], beta0),
              "checkpoints": checkpoints}
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return report


def live(port_name: str, rounds: int, report_path: Path, say=print) -> dict:
    """Real strikes: a check round, ``rounds`` guided training rounds, and a final check round.

    Every strike is learned by the AxlCORE and by the CPU float32 OS-ELM at the same time; after each one the
    two betas and the model input are read back, so every strike can be replayed against both afterwards.
    """
    import serial
    from pc.acrylic_pan_monitor.calibrate import area_label

    model = load_model()
    alpha32 = model["alpha"].astype(np.float32)
    beta0 = from_bfloat16_bits(model["beta_bits"]).astype(np.float64)
    hits: list[dict] = []
    with serial.Serial(port_name, 115_200, timeout=0.05, write_timeout=0.5) as port:
        board = Board(port)
        board.begin()
        engine, cpu = board.beta()

        def strike(phase: str, round_index: int, area: int, train: bool) -> None:
            nonlocal engine, cpu
            say(f"[{phase} {round_index}] {area_label(area)} を叩いてください")
            result = board.client.hit(area if train else None)
            record = {"phase": phase, "round": round_index, "area": area, "train": train,
                      "board_predicted": int(result.predicted_class), "train_us": int(result.train_us),
                      "trained": bool(result.trained), "input": board.last_input().tolist(),
                      "engine_before": engine.tolist(), "cpu_before": cpu.tolist()}
            if train:
                engine, cpu = board.beta()
            record["engine_after"], record["cpu_after"] = engine.tolist(), cpu.tolist()
            hits.append(record)
            say(f"    認識: {area_label(result.predicted_class)}"
                f"{'  (学習 ' + str(result.train_us // 1000) + ' ms)' if train else ''}")

        for area in range(CLASS_COUNT):
            strike("確認(学習前)", 0, area, False)
        for round_index in range(1, rounds + 1):
            for area in range(CLASS_COUNT):
                strike("学習", round_index, area, True)
        for area in range(CLASS_COUNT):
            strike("確認(学習後)", 0, area, False)

    # Replay: what would each beta have recognised, and how far apart did the two betas drift?
    targets = np.asarray([h["area"] for h in hits])
    inputs = np.asarray([h["input"] for h in hits], dtype=np.uint16)
    hidden = hidden_layer(from_bfloat16_bits(inputs), model["alpha"])
    trained = np.asarray([h["train"] for h in hits])
    reference = os_elm_update(beta0, model["p0"], hidden[trained], targets[trained], "float64")[0]

    def predict(bits: np.ndarray, beta: np.ndarray) -> int:
        if not np.isfinite(beta).all():
            return -1
        scores = mcu_reference(from_bfloat16_bits(bits[None, :]), alpha32, beta.astype(np.float32))
        return int(np.argmax(scores[0]))

    rows = []
    for hit, bits in zip(hits, inputs):
        engine_before, cpu_before = np.asarray(hit["engine_before"]), np.asarray(hit["cpu_before"])
        rows.append({"phase": hit["phase"], "round": hit["round"], "area": hit["area"],
                     "engine_predicted": predict(bits, engine_before), "cpu_predicted": predict(bits, cpu_before),
                     "board_predicted": hit["board_predicted"],
                     "engine_vs_cpu_max": float(np.abs(np.asarray(hit["engine_after"]) - np.asarray(hit["cpu_after"])).max()),
                     "engine_nonfinite": int((~np.isfinite(np.asarray(hit["engine_after"]))).sum())})
    summary = {}
    for phase in ("確認(学習前)", "学習", "確認(学習後)"):
        members = [r for r in rows if r["phase"] == phase]
        summary[phase] = {
            "hits": len(members),
            "engine_accuracy": float(np.mean([r["engine_predicted"] == r["area"] for r in members])),
            "cpu_accuracy": float(np.mean([r["cpu_predicted"] == r["area"] for r in members])),
            "board_reported_accuracy": float(np.mean([r["board_predicted"] == r["area"] for r in members]))}
    final = hits[-1]
    summary["final_engine_vs_cpu_max"] = float(np.abs(np.asarray(final["engine_after"]) - np.asarray(final["cpu_after"])).max())
    summary["final_engine_vs_float64_max"] = float(np.abs(np.asarray(final["engine_after"]) - reference).max())
    summary["final_cpu_vs_float64_max"] = float(np.abs(np.asarray(final["cpu_after"]) - reference).max())
    summary["engine_nonfinite_max"] = max(r["engine_nonfinite"] for r in rows)
    report = {"rounds": rounds, "summary": summary, "per_hit": rows, "raw": hits}
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(report, ensure_ascii=False) + "\n", encoding="utf-8")
    say("")
    for phase, entry in summary.items():
        if isinstance(entry, dict):
            say(f"{phase}: AxlCORE {entry['engine_accuracy']:.1%}  CPU {entry['cpu_accuracy']:.1%}  ({entry['hits']}打)")
    say(f"最後のβの差(AxlCORE vs CPU)の最大: {summary['final_engine_vs_cpu_max']:.4f}、"
        f"非有限値: {summary['engine_nonfinite_max']}")
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("export")
    runner = sub.add_parser("run")
    runner.add_argument("--port", required=True)
    runner.add_argument("--updates", type=int, default=480)
    runner.add_argument("--checkpoint", type=int, default=24)
    live_parser = sub.add_parser("live")
    live_parser.add_argument("--port", required=True)
    live_parser.add_argument("--rounds", type=int, default=10)
    parser.add_argument("--sessions-root", type=Path, default=Path("data/raw/sessions_2point"))
    parser.add_argument("--report", type=Path, default=REPORT)
    args = parser.parse_args()
    if args.command == "export":
        export(args.sessions_root)
    elif args.command == "live":
        live(args.port, args.rounds, args.report.with_name("live_report.json"))
    else:
        run(args.sessions_root, args.port, args.updates, args.checkpoint, args.report)


if __name__ == "__main__":
    main()
